// Generates worker/shims/services-index.ts: the curated replacement for
// server/src/services/index.ts used by the Worker bundle (see worker/build.mjs).
//
// Why: 33 of 54 route modules import the services barrel, and the barrel
// re-exports the whole execution plane. Only the names that mounted routes use
// are exported here. A name whose source module is Workers-safe is re-exported
// from the real module; a name whose source module reaches Node-only code is
// exported as a stub that throws on first use, so a route that needs it fails
// loudly instead of dragging Node-only modules into the bundle.
//
// Usage: node worker/scripts/gen-services-index.mjs  (from server/)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, normalize, relative } from "node:path";

const SRC = new URL("../../src/", import.meta.url).pathname;
const OUT = new URL("../shims/services-index.ts", import.meta.url).pathname;

// Names are derived from the route modules mounted in worker/index.ts: every
// `import ... from "../src/routes/<name>.js"` there is scanned for what it
// imports from "../services/index.js". EXTRA_NEEDED covers names reached some
// other way (for example a middleware that imports the barrel).
const INDEX = new URL("../index.ts", import.meta.url).pathname;
const EXTRA_NEEDED = [];
function neededNames() {
  const index = readFileSync(INDEX, "utf8");
  const routeFiles = [...index.matchAll(/from\s+"\.\.\/src\/routes\/([^"]+)\.js"/g)].map((m) => join(SRC, "routes", m[1] + ".ts"));
  const names = new Set(EXTRA_NEEDED);
  for (const file of routeFiles) {
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(/import\s+(type\s+)?\{([^}]*)\}\s+from\s+"\.\.\/services\/index\.js"/g)) {
      for (let name of m[2].split(",")) {
        name = name.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
        if (name) names.add(name);
      }
    }
  }
  return [...names];
}
const NEEDED = neededNames();
// Type-only names (erased at build time).
const TYPES = new Set(); // filled from the barrel below (export type {...})

// Source modules whose static import graph reaches Node-only builtins
// (node:fs, child_process, net, dns, tls, http, readline, ...). Stubbed.
const NODE_BOUND = new Set([
  "heartbeat", "issues", "status-cards", "company-portability",
  "routines", "approvals", "secrets", "feedback", "smoke-lab",
  "skills-catalog", "built-in-agents",
]);

const barrel = readFileSync(join(SRC, "services/index.ts"), "utf8");
const source = new Map();
for (const m of barrel.matchAll(/export\s+(type\s+)?\{([^}]*)\}\s+from\s+"([^"]+)"/g)) {
  for (let name of m[2].split(",")) {
    const isType = Boolean(m[1]) || /^type\s+/.test(name.trim());
    name = name.trim().replace(/^type\s+/, "");
    if (!name) continue;
    const [orig, exported = orig] = name.split(/\s+as\s+/);
    source.set(exported.trim(), { module: m[3], orig: orig.trim() });
    if (isType) TYPES.add(exported.trim());
  }
}

const lines = [
  "// GENERATED by worker/scripts/gen-services-index.mjs — do not edit by hand.",
  "// Curated replacement for server/src/services/index.ts in the Worker bundle.",
  "",
  "// Lazy stub. Route factories build services eagerly and read properties off",
  "// them (`heartbeatService(db).wakeup`), so construction and property access",
  "// return proxies; the first call, await, string conversion, or JSON",
  "// serialization of the result throws.",
  "function unavailable(name: string): any {",
  "  const fail = (): never => { throw new Error(`${name} is not available on the Cloudflare Worker yet`); };",
  "  const child: any = new Proxy(fail, {",
  "    apply: fail,",
  "    construct: fail,",
  "    get: (_t, prop) => (prop === \"then\" || prop === \"toJSON\" || prop === Symbol.toPrimitive || prop === \"toString\" || prop === \"valueOf\" ? fail() : child),",
  "  });",
  "  return new Proxy(fail, { apply: () => child, construct: () => child, get: (_t, prop) => (prop === \"then\" ? undefined : child) });",
  "}",
  "",
];
const missing = [];
for (const name of NEEDED) {
  const s = source.get(name);
  if (!s) { missing.push(name); continue; }
  const modName = s.module.replace(/^\.\//, "").replace(/\.js$/, "");
  const rel = "../../src/services/" + s.module.replace(/^\.\//, "");
  if (TYPES.has(name)) { lines.push(`export type { ${s.orig === name ? name : `${s.orig} as ${name}`} } from "${rel}";`); continue; }
  if (NODE_BOUND.has(modName)) {
    lines.push(`export const ${name} = unavailable("${name}") as unknown as typeof import("${rel}").${s.orig};`);
  } else {
    lines.push(`export { ${s.orig === name ? name : `${s.orig} as ${name}`} } from "${rel}";`);
  }
}
if (missing.length) { console.error("not found in services/index.ts:", missing.join(", ")); process.exit(1); }
writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`wrote ${relative(process.cwd(), OUT)} (${NEEDED.length} names, ${[...NEEDED].filter(n => NODE_BOUND.has((source.get(n)?.module || "").replace(/^\.\//, "").replace(/\.js$/, ""))).length} stubbed)`);
