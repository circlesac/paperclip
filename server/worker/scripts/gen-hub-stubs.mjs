// Generates worker/shims/hubs/<name>.ts: throwing stubs for execution-plane hub
// modules that route code imports but the Worker cannot run (child processes,
// git worktrees, local secrets files, sandbox runtimes). worker/build.mjs
// redirects the real module paths to these stubs, so a route that only
// *imports* a hub bundles and runs, and a route that *calls* into one fails
// loudly with "<module>.<name> is not available on the Cloudflare Worker yet".
//
// Every value export of the real module (including `export * from` chains) is
// emitted as a function that throws; type exports are re-exported from the real
// module (erased at build time). Usage (from server/):
//   node worker/scripts/gen-hub-stubs.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, normalize, relative, resolve } from "node:path";

const SRC = resolve(new URL("../../src/", import.meta.url).pathname);
const OUT_DIR = resolve(new URL("../shims/hubs/", import.meta.url).pathname);

// Real module (relative to server/src) → stub file name under worker/shims/hubs.
export const HUBS = {
  "services/native-runtime/index.ts": "native-runtime.ts",
  "adapters/registry.ts": "adapters-registry.ts",
  "adapters/index.ts": "adapters-index.ts",
  "storage/index.ts": "storage-index.ts",
  "secrets/provider-registry.ts": "secrets-provider-registry.ts",
  "services/execution-workspaces.ts": "execution-workspaces.ts",
  "services/tool-gateway.ts": "tool-gateway.ts",
  // Service modules whose import graph reaches the execution plane. The curated
  // services barrel already stubs their exports; redirecting the files too makes
  // direct imports (e.g. services/issue-tree-control.ts → ./issues.js) consistent.
  "services/issues.ts": "services-issues.ts",
  "services/heartbeat.ts": "services-heartbeat.ts",
  "services/companies.ts": "services-companies.ts",
  "services/status-cards.ts": "services-status-cards.ts",
  "services/routines.ts": "services-routines.ts",
  "services/agents.ts": "services-agents.ts",
  "services/approvals.ts": "services-approvals.ts",
  "services/secrets.ts": "services-secrets.ts",
  "services/feedback.ts": "services-feedback.ts",
  "services/smoke-lab.ts": "services-smoke-lab.ts",
  "services/company-portability.ts": "services-company-portability.ts",
};

function exportsOf(path, seen = new Set()) {
  if (seen.has(path) || !existsSync(path)) return { values: new Map(), types: new Set() };
  seen.add(path);
  const s = readFileSync(path, "utf8");
  const values = new Map();
  const types = new Set();
  for (const m of s.matchAll(/^export\s+(?:async\s+)?(function\*?|const|let|var|class|enum)\s+([A-Za-z_$][\w$]*)/gm)) values.set(m[2], m[1]);
  for (const m of s.matchAll(/^export\s+(interface|type)\s+([A-Za-z_$][\w$]*)/gm)) types.add(m[2]);
  for (const m of s.matchAll(/^export\s+(type\s+)?\{([^}]*)\}(?:\s+from\s+"([^"]+)")?/gm)) {
    for (let name of m[2].split(",")) {
      name = name.trim();
      if (!name) continue;
      const isType = Boolean(m[1]) || name.startsWith("type ");
      name = name.replace(/^type\s+/, "").split(/\s+as\s+/).pop().trim();
      if (isType) types.add(name); else values.set(name, "reexport");
    }
  }
  for (const m of s.matchAll(/^export\s+\*\s+from\s+"([^"]+)"/gm)) {
    const p = normalize(join(dirname(path), m[1])).replace(/\.js$/, ".ts");
    const sub = exportsOf(p, seen);
    for (const [k, v] of sub.values) values.set(k, v);
    for (const t of sub.types) types.add(t);
  }
  return { values, types };
}

mkdirSync(OUT_DIR, { recursive: true });
for (const [real, stubName] of Object.entries(HUBS)) {
  const realPath = join(SRC, real);
  const { values, types } = exportsOf(realPath);
  const relReal = relative(OUT_DIR, realPath).replace(/\.ts$/, ".js");
  const modLabel = real.replace(/\.ts$/, "");
  const lines = [
    `// GENERATED by worker/scripts/gen-hub-stubs.mjs from server/src/${real} — do not edit.`,
    `// Every value export throws; the Worker cannot run this module.`,
    "",
    `// Lazy: calling/constructing returns a proxy; the first property access throws.`,
    `function unavailable(name: string): any {`,
    `  const fail = (): never => { throw new Error(\`${modLabel}.\${name} is not available on the Cloudflare Worker yet\`); };`,
    `  const proxy: any = new Proxy(fail, { apply: () => proxy, construct: () => proxy, get: (_t, prop) => (prop === "then" ? undefined : fail()) });`,
    `  return proxy;`,
    `}`,
    "",
  ];
  for (const name of [...values.keys()].sort()) {
    lines.push(`export const ${name} = unavailable("${name}") as unknown as typeof import("${relReal}").${name};`);
  }
  if (types.size) lines.push("", `export type { ${[...types].sort().join(", ")} } from "${relReal}";`);
  writeFileSync(join(OUT_DIR, stubName), lines.join("\n") + "\n");
  console.log(`wrote shims/hubs/${stubName}: ${values.size} values, ${types.size} types`);
}
